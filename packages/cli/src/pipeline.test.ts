import { fileURLToPath } from "node:url";

import type { Stack } from "@formation/registry";
import { describe, expect, it } from "vitest";

import type { GeneratedForm } from "./pipeline.js";
import { generateForm } from "./pipeline.js";

// The fixtures are the golden project's own schemas, so what is asserted here
// is the same input whose output examples/zustand-mui typechecks and runs.
const fixture = (name: string): string =>
  fileURLToPath(new URL(`../../../examples/zustand-mui/schemas/${name}`, import.meta.url));

const outDir = fileURLToPath(new URL("../../../examples/zustand-mui/src/out", import.meta.url));

const stack = (schemaLibrary: Stack["schemaLibrary"], uiMajor = 9): Stack => ({
  framework: "react",
  stateLibrary: "zustand",
  uiLibrary: "mui",
  uiMajor,
  schemaLibrary,
  syntax: "ts",
  testRunners: [],
});

const generate = async (
  name: string,
  schemaLibrary: Stack["schemaLibrary"],
  extra: Readonly<{ select?: string; exportName?: string; name?: string }> = {},
): Promise<GeneratedForm> => {
  const outcome = await generateForm({
    schemaPath: fixture(name),
    stack: stack(schemaLibrary),
    outDir,
    ...extra,
  });

  if (outcome.kind === "failed") {
    throw new Error(outcome.diagnostics.map((diagnostic) => diagnostic.message).join("; "));
  }
  return outcome.value;
};

const contentOf = (form: GeneratedForm, path: string): string =>
  form.files.find((file) => file.path === path)?.content ?? "";

describe("generateForm", () => {
  it("produces the same five-file folder for every input kind", async () => {
    const forms = await Promise.all([
      generate("profile.ts", "zod"),
      generate("order.json", "json-schema"),
      generate("petstore.yaml", "openapi", { select: "NewPet" }),
    ]);

    expect(forms.map((form) => form.folder)).toEqual(["ProfileForm", "OrderForm", "NewPetForm"]);
    expect(forms.map((form) => form.files.map((file) => file.path))).toEqual([
      ["schema.ts", "store.ts", "controls.tsx", "ProfileForm.tsx", "index.ts"],
      ["schema.ts", "store.ts", "controls.tsx", "OrderForm.tsx", "index.ts"],
      ["schema.ts", "store.ts", "controls.tsx", "NewPetForm.tsx", "index.ts"],
    ]);
  });

  it("re-exports a Zod schema instead of regenerating a weaker copy of it", async () => {
    const form = await generate("profile.ts", "zod");

    // Relative to the form folder, extensionless, forward slashes on every OS.
    expect(contentOf(form, "schema.ts")).toContain(
      'export { profileSchema } from "../../../schemas/profile";',
    );
    expect(contentOf(form, "schema.ts")).not.toContain("z.object");
  });

  it("generates the validator when the input is a document", async () => {
    const form = await generate("order.json", "json-schema");

    expect(contentOf(form, "schema.ts")).toContain("export const orderSchema = z.object({");
  });

  it("honors --name over the schema's own", async () => {
    const form = await generate("order.json", "json-schema", { name: "Checkout" });

    expect(form.componentName).toBe("CheckoutForm");
    expect(contentOf(form, "store.ts")).toContain("export const useCheckoutStore");
  });

  it("gives the folder a public API through its index", async () => {
    const index = contentOf(await generate("order.json", "json-schema"), "index.ts");

    expect(index).toContain('export { OrderForm } from "./OrderForm";');
    expect(index).toContain('export { orderSchema } from "./schema";');
    expect(index).toContain(
      'export { useOrderStore, useOrderForm, orderInitialValues } from "./store";',
    );
  });

  it("stamps every file as generated-and-yours", async () => {
    const form = await generate("consent.json", "json-schema");

    expect(
      form.files.every((file) => file.content.startsWith("// Generated by @formation/cli")),
    ).toBe(true);
  });

  it("emits no control and no import for a kind the form does not use", async () => {
    const form = await generate("consent.json", "json-schema");
    const controls = contentOf(form, "controls.tsx");

    expect(controls).toContain("export const BooleanControl");
    expect(controls).not.toMatch(/TextControl|NumberControl|ChoiceControl|DateControl|TextField/);
  });

  it("leaves a stub and a warning where a field has no control, and still generates", async () => {
    // `metadata` is a record: no fixed properties, so nothing to bind.
    const outcome = await generateForm({
      schemaPath: fixture("order.json"),
      stack: stack("json-schema"),
      outDir,
    });
    const files = outcome.kind === "ok" ? outcome.value : undefined;

    expect(files && contentOf(files, "OrderForm.tsx")).toContain(
      'TODO(formation): "metadata" has no control',
    );
    // Stubbed in the UI, but still present everywhere the data lives.
    expect(files && contentOf(files, "store.ts")).toContain("metadata: unknown;");
    expect(files && contentOf(files, "schema.ts")).toContain("metadata: z.unknown()");
    expect(
      outcome.diagnostics.some(
        (entry) => entry.code === "schema/unsupported-node" && entry.path?.[0] === "metadata",
      ),
    ).toBe(true);
  });

  it("gives a discriminated union a branch picker and a block per branch", async () => {
    const form = await generate("profile.ts", "zod");
    const component = contentOf(form, "ProfileForm.tsx");

    expect(component).toContain("const variant = useProfileVariant(path);");
    expect(component).toContain('{variant.value === "card" ? (');
    // Branch fields bind at ordinary paths beneath the union.
    expect(component).toContain("path={`${path}.last4`}");
    // A union as a list row is the same component, addressed per row.
    expect(component).toContain("<ProfileNotificationsVariants path={`${path}.${index}`} />");
  });

  it("reads an OpenAPI discriminator whose branches sit behind $refs", async () => {
    const form = await generate("petstore.yaml", "openapi", { select: "NewPet" });

    expect(contentOf(form, "schema.ts")).toContain('housing: z.discriminatedUnion("kind", [');
    expect(contentOf(form, "NewPetForm.tsx")).toContain(
      '<MenuItem value="outdoor">Outdoor</MenuItem>',
    );
  });

  it("emits identical source for MUI 7 and MUI 9", async () => {
    // Nothing the adapter uses differs between the two majors today. If this
    // starts failing, the majors have diverged and the docs that say
    // otherwise need to change with it.
    const [seven, nine] = await Promise.all(
      [7, 9].map((major) =>
        generateForm({
          schemaPath: fixture("order.json"),
          stack: stack("json-schema", major),
          outDir,
        }),
      ),
    );

    expect(seven?.kind === "ok" && seven.value.files).toEqual(
      nine?.kind === "ok" && nine.value.files,
    );
  });
});

describe("failures come back as diagnostics, not exceptions", () => {
  const failure = async (
    name: string,
    schemaLibrary: Stack["schemaLibrary"],
    extra: Readonly<{ select?: string; exportName?: string }> = {},
  ): Promise<string> => {
    const outcome = await generateForm({
      schemaPath: fixture(name),
      stack: stack(schemaLibrary),
      outDir,
      ...extra,
    });

    return outcome.kind === "failed" ? (outcome.diagnostics[0]?.message ?? "") : "generated";
  };

  it("reports a missing file", async () => {
    expect(await failure("nope.json", "json-schema")).toMatch(/could not be read/);
  });

  it("asks which schema when an OpenAPI document holds several", async () => {
    expect(await failure("petstore.yaml", "openapi")).toMatch(/pick one with --select/);
  });

  it("reports a Zod export that does not exist, listing the ones that do", async () => {
    expect(await failure("profile.ts", "zod", { exportName: "nope" })).toMatch(
      /Export "nope" is not a Zod schema\. Schema exports found: profileSchema/,
    );
  });
});
