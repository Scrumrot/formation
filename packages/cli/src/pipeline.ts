import { readFile } from "node:fs/promises";
import { extname, join, relative } from "node:path";

import type {
  Diagnostic,
  FormIR,
  GeneratedFile,
  Outcome,
  StateAdapter,
  UiAdapter,
} from "@formation/core";
import { assembleForm, camelCase, failed, hasErrors, ok } from "@formation/core";
import { EXTENSION as TSX, printModule } from "@formation/framework-react";
import { fromJsonSchema } from "@formation/ingest-json-schema";
import { fromZodModule } from "@formation/ingest-zod";
import type { Stack, StateLibraryId, UiLibraryId } from "@formation/registry";
import { emitZodSchema } from "@formation/schema-zod";
import { STORE_MODULE, zustandAdapter } from "@formation/state-zustand";
import { muiAdapter, muiMajors } from "@formation/ui-mui";
import { parse as parseYaml } from "yaml";

/**
 * The whole compiler, end to end:
 *
 *   schema file → ingest → FormIR → state adapter ┐
 *                                  → UI adapter   ┴→ ComponentIR → printer → files
 *
 * Reading the schema is the only I/O in here; nothing is written. The caller
 * decides what to do with the files (write them, print them, diff them), which
 * is what lets a dry run and the real thing share every line of this.
 */

/** Module holding the validator, relative to the form folder. */
const SCHEMA_MODULE = "schema";

const HEADER = "// Generated by @formation/cli. This file is yours: edit it freely.\n";

export type GenerateRequest = Readonly<{
  /** Absolute path of the schema file. */
  schemaPath: string;
  stack: Stack;
  /** Absolute directory the form's folder is created in. */
  outDir: string;
  /** JSON Schema / OpenAPI: which schema in the document. */
  select?: string;
  /** Zod: which export holds the schema. */
  exportName?: string;
  /** Overrides the name derived from the schema. */
  name?: string;
}>;

export type GeneratedForm = Readonly<{
  componentName: string;
  /** Folder name inside `outDir`. */
  folder: string;
  /** Paths relative to that folder; content not yet formatted. */
  files: readonly GeneratedFile[];
}>;

// Partial, not exhaustive: the registry also lists *planned* libraries, which
// have no adapter by definition. `adapters.test.ts` pins the other direction —
// every library the registry calls available must have an entry here.
export const stateAdapters: Readonly<Partial<Record<StateLibraryId, StateAdapter>>> = {
  zustand: zustandAdapter,
};

export const uiAdapters: Readonly<
  Partial<Record<UiLibraryId, (major: number | undefined) => UiAdapter | undefined>>
> = {
  mui: (major) => {
    const supported = muiMajors.find((candidate) => candidate === major);

    return supported === undefined ? undefined : muiAdapter(supported);
  },
};

type Ingested = Readonly<{ form: FormIR; schemaFile: GeneratedFile; schemaExport: string }>;

const unreadable = (message: string, source: string): Diagnostic => ({
  severity: "error",
  code: "schema/unreadable",
  message,
  source,
});

/** `../../schemas/profile` — how the generated folder imports the user's schema module. */
const importSpecifier = (fromDir: string, target: string): string => {
  const path = relative(fromDir, target).split("\\").join("/");
  const bare = path.slice(0, path.length - extname(path).length);

  return bare.startsWith(".") ? bare : `./${bare}`;
};

const ingestZod = async (request: GenerateRequest, formDir: (name: string) => string) => {
  const outcome = await fromZodModule(request.schemaPath, {
    ...(request.exportName === undefined ? {} : { exportName: request.exportName }),
    ...(request.name === undefined ? {} : { name: request.name }),
  });

  if (outcome.kind === "failed") return outcome;

  const { form, exportName } = outcome.value;
  const schemaExport = exportName === "default" ? `${camelCase(form.name)}Schema` : exportName;
  const from = importSpecifier(formDir(form.name), request.schemaPath);

  // The original schema is re-exported, never re-emitted: refinements,
  // transforms and custom messages have no JSON Schema form, so a regenerated
  // copy would validate less than the schema the user wrote.
  const content =
    exportName === "default"
      ? `export { default as ${schemaExport} } from ${JSON.stringify(from)};\n`
      : `export { ${schemaExport} } from ${JSON.stringify(from)};\n`;

  return ok<Ingested>(
    { form, schemaExport, schemaFile: { path: `${SCHEMA_MODULE}.ts`, content } },
    outcome.diagnostics,
  );
};

const parseDocument = (
  text: string,
  path: string,
):
  | Readonly<{ kind: "parsed"; document: unknown }>
  | Readonly<{ kind: "invalid"; message: string }> => {
  try {
    // YAML is a superset of JSON, but JSON.parse gives the better error message
    // for a `.json` file, so each extension gets its own parser.
    return {
      kind: "parsed",
      document: /\.ya?ml$/i.test(path)
        ? (parseYaml(text) as unknown)
        : (JSON.parse(text) as unknown),
    };
  } catch (cause) {
    return { kind: "invalid", message: cause instanceof Error ? cause.message : String(cause) };
  }
};

const ingestDocument = async (request: GenerateRequest): Promise<Outcome<Ingested>> => {
  const text = await readFile(request.schemaPath, "utf8").catch(() => undefined);

  if (text === undefined) {
    return failed([unreadable("The schema file could not be read.", request.schemaPath)]);
  }

  const parsed = parseDocument(text, request.schemaPath);

  if (parsed.kind === "invalid") {
    return failed([
      unreadable(`The schema file is not valid: ${parsed.message}`, request.schemaPath),
    ]);
  }

  const outcome = fromJsonSchema(parsed.document, {
    source: request.schemaPath,
    ...(request.select === undefined ? {} : { select: request.select }),
    ...(request.name === undefined ? {} : { name: request.name }),
  });

  if (outcome.kind === "failed") return outcome;

  const form = outcome.value;
  const schemaExport = `${camelCase(form.name)}Schema`;

  return ok<Ingested>(
    {
      form,
      schemaExport,
      // A document describes the data but cannot check it, so the validator the
      // store needs is generated here.
      schemaFile: { path: `${SCHEMA_MODULE}.ts`, content: emitZodSchema(form, schemaExport) },
    },
    outcome.diagnostics,
  );
};

const indexFile = (
  componentName: string,
  schemaExport: string,
  values: readonly string[],
  types: readonly string[],
): GeneratedFile => ({
  path: "index.ts",
  content: [
    `export { ${componentName} } from "./${componentName}";`,
    `export type { ${componentName}Props } from "./${componentName}";`,
    `export { ${schemaExport} } from "./${SCHEMA_MODULE}";`,
    `export { ${values.join(", ")} } from "./${STORE_MODULE}";`,
    `export type { ${types.join(", ")} } from "./${STORE_MODULE}";`,
    "",
  ].join("\n"),
});

const missingAdapter = (kind: string, id: string): Diagnostic => ({
  severity: "error",
  code: "emit/capability-unsupported",
  message: `The registry lists ${kind} "${id}" as available, but this CLI has no adapter for it.`,
});

export const generateForm = async (request: GenerateRequest): Promise<Outcome<GeneratedForm>> => {
  const folderOf = (name: string): string => `${name}Form`;
  const formDir = (name: string): string => join(request.outDir, folderOf(name));

  // No `default` arm: a schema library the registry marks available must be
  // given an ingest route here, or this fails to compile.
  const ingested = await ((): Promise<Outcome<Ingested>> => {
    switch (request.stack.schemaLibrary) {
      case "zod":
        return ingestZod(request, formDir);
      case "json-schema":
      case "openapi":
        return ingestDocument(request);
      case "typebox":
      case "valibot":
      case "arktype":
      case "yup":
        return Promise.resolve(
          failed([missingAdapter("schema library", request.stack.schemaLibrary)]),
        );
    }
  })();

  if (ingested.kind === "failed") return ingested;

  const { form, schemaExport, schemaFile } = ingested.value;
  const state = stateAdapters[request.stack.stateLibrary];
  const ui = uiAdapters[request.stack.uiLibrary]?.(request.stack.uiMajor);

  if (state === undefined || ui === undefined) {
    return failed([
      ...ingested.diagnostics,
      ...(state === undefined ? [missingAdapter("state library", request.stack.stateLibrary)] : []),
      ...(ui === undefined ? [missingAdapter("UI library", request.stack.uiLibrary)] : []),
    ]);
  }

  const stateOutput = state({ form, schemaModule: SCHEMA_MODULE, schemaExport });
  const assembled = assembleForm(form, stateOutput.binding, ui);
  const diagnostics = [
    ...ingested.diagnostics,
    ...stateOutput.diagnostics,
    ...assembled.diagnostics,
  ];

  if (hasErrors(diagnostics)) return failed(diagnostics);

  const components: readonly GeneratedFile[] = assembled.modules.map((module) => ({
    path: `${module.name}.${TSX}`,
    content: printModule(module, assembled.imports),
  }));

  const files = [
    schemaFile,
    ...stateOutput.files,
    ...components,
    indexFile(
      assembled.componentName,
      schemaExport,
      stateOutput.binding.publicValues,
      stateOutput.binding.publicTypes,
    ),
  ].map((file) => ({ ...file, content: `${HEADER}${file.content}` }));

  return ok(
    { componentName: assembled.componentName, folder: folderOf(form.name), files },
    diagnostics,
  );
};
